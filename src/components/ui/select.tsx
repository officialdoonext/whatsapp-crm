"use client"

import * as React from "react"
import { Select as SelectPrimitive } from "@base-ui/react/select"

import { cn } from "@/lib/utils"
import { ChevronDownIcon, CheckIcon, ChevronUpIcon, Search as SearchIcon } from "lucide-react"

const Select = SelectPrimitive.Root

interface SelectSearchContextType {
  searchQuery: string;
  setSearchQuery: (query: string) => void;
}

const SelectSearchContext = React.createContext<SelectSearchContextType>({
  searchQuery: "",
  setSearchQuery: () => {},
});

function extractText(node: React.ReactNode): string {
  if (typeof node === "string" || typeof node === "number") return String(node);
  if (Array.isArray(node)) return node.map(extractText).join(" ");
  if (React.isValidElement(node) && (node.props as { children?: React.ReactNode })?.children) {
    return extractText((node.props as { children?: React.ReactNode }).children);
  }
  return "";
}

