function SelectItem({
  className,
  children,
  value,
  ...props
}: SelectPrimitive.Item.Props & { value?: string }) {
  const { searchQuery } = React.useContext(SelectSearchContext)

  const matches = React.useMemo(() => {
    if (!searchQuery.trim()) return true;
    const text = `${extractText(children)} ${value || ""}`.toLowerCase();
    return text.includes(searchQuery.trim().toLowerCase());
  }, [children, value, searchQuery]);

  if (!matches) {
    return null;
  }

  return (
    <SelectPrimitive.Item
      data-slot="select-item"
      className={cn(
        "relative flex w-full cursor-pointer items-center gap-1.5 rounded-sm py-1.5 pr-8 pl-2 text-xs sm:text-sm outline-hidden select-none focus:bg-accent focus:text-accent-foreground not-data-[variant=destructive]:focus:**:text-accent-foreground data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2",
        className
      )}
      {...props}
    >
      <SelectPrimitive.ItemText className="flex flex-1 shrink-0 gap-2 whitespace-nowrap">
        {children}
      </SelectPrimitive.ItemText>
      <SelectPrimitive.ItemIndicator
        render={
          <span className="pointer-events-none absolute right-2 flex size-4 items-center justify-center" />
        }
      >
        <CheckIcon className="pointer-events-none" />
      </SelectPrimitive.ItemIndicator>
    </SelectPrimitive.Item>
  )
}

