/**
 * Builds an Excel binary buffer (.xlsx) of the 50 sample products.
 */
export function generateSampleProductsWorkbook(): Uint8Array {
  const worksheet = XLSX.utils.json_to_sheet(SAMPLE_50_PRODUCTS);

  // Set column widths for comfortable reading in Excel
  worksheet['!cols'] = [
    { wch: 32 }, // Product Name
    { wch: 18 }, // Short Code
    { wch: 22 }, // Category
    { wch: 45 }, // Description
    { wch: 12 }, // Food Type
    { wch: 14 }, // List Price
    { wch: 14 }, // Sale Price
    { wch: 12 }, // Tax Type
    { wch: 10 }, // Tax %
    { wch: 10 }, // CGST %
    { wch: 10 }, // SGST %
    { wch: 16 }, // Variant Label
    { wch: 22 }, // Variant Value
    { wch: 20 }, // Variant List Price
    { wch: 20 }, // Variant Sale Price
    { wch: 35 }, // Image URL
    { wch: 14 }, // Energy
    { wch: 12 }, // Protein
    { wch: 18 }, // Carbs
    { wch: 12 }, // Fat
  ];

  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Master Products (50)');

  const buffer = XLSX.write(workbook, { bookType: 'xlsx', type: 'buffer' });
  return buffer;
}

/**
 * Builds a UTF-8 CSV string (with BOM for Excel) of the 50 sample products.
 */
export function generateSampleProductsCsv(): string {
  const worksheet = XLSX.utils.json_to_sheet(SAMPLE_50_PRODUCTS);
  const csv = XLSX.utils.sheet_to_csv(worksheet);
  // Prepend UTF-8 BOM so Microsoft Excel opens it with perfect character encoding
  return '\uFEFF' + csv;
}
